"""python -m tools.yume_urdf robot.urdf [--id ID] [--friction LINK=V ...] [--layer NAME ...]
                                      [--spawn X,Y,Z] [--out FILE]

Writes {"definitions": [def]} (and one initial instance with --spawn) as
JSON. Without --out, it prints to stdout. Warnings go to stderr.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .convert import URDFError, convert


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m tools.yume_urdf")
    ap.add_argument("urdf", type=Path)
    ap.add_argument("--id", help="def id (default: the robot name)")
    ap.add_argument("--friction", action="append", default=[], metavar="LINK=V",
                    help="friction of one link, for example caster=0 (URDF has no friction)")
    ap.add_argument("--layer", action="append", default=[], metavar="NAME",
                    help="a collision layer name from @lib.physics.layers (repeat for more)")
    ap.add_argument("--spawn", metavar="X,Y,Z", help="also write one initial instance at this position")
    ap.add_argument("--out", type=Path)
    a = ap.parse_args(argv)
    friction = {}
    for item in a.friction:
        k, _, v = item.partition("=")
        friction[k] = float(v)
    try:
        d, warnings = convert(a.urdf.read_text(encoding="utf-8"), a.id, friction, layers=a.layer)
    except URDFError as e:
        print(f"[yume_urdf] error: {e}", file=sys.stderr)
        return 1
    for w in warnings:
        print(f"[yume_urdf] warning: {w}", file=sys.stderr)
    doc = {"_comment": f"Generated by tools/yume_urdf from {a.urdf.name}.", "definitions": [d]}
    if a.spawn:
        doc["initial_instances"] = [{"def": d["id"], "id": f"{d['id']}_1",
                                     "position": [float(v) for v in a.spawn.split(",")]}]
    text = json.dumps(doc, indent=2) + "\n"
    if a.out:
        a.out.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
